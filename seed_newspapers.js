async function main() {
  console.log('🗞️  开始写入全国报纸数据...\n')

  let inserted = 0
  let skipped = 0
  let errors = 0

  for (const [name, province, city, pricePerWord, minWords, level, coverage] of newspapers) {
    try {
      // 检查是否已存在（按名称去重）
      const existing = await prisma.newspaper.findFirst({
        where: { name },
      })

      if (existing) {
        // 更新已有记录
        await prisma.newspaper.update({
          where: { id: existing.id },
          data: {
            province,
            city: city || null,
            pricePerWord: parseFloat(pricePerWord),
            minWords: parseInt(minWords),
            level: parseInt(level),
            coverage: parseInt(coverage),
            status: 1,
          },
        })
        skipped++
        process.stdout.write(`  ✅ 更新: ${name} (${province})\n`)
      } else {
        await prisma.newspaper.create({
          data: {
            name,
            province,
            city: city || null,
            pricePerWord: parseFloat(pricePerWord),
            minWords: parseInt(minWords),
            level: parseInt(level),
            coverage: parseInt(coverage),
            status: 1,
            sort: 0,
          },
        })
        inserted++
        process.stdout.write(`  ✅ 新增: ${name} (${province})\n`)
      }
    } catch (err) {
      errors++
      console.error(`  ❌ 错误 [${name}]: ${err.message}`)
    }
  }

  console.log(`\n📊 完成: 新增 ${inserted} 条, 更新 ${skipped} 条, 错误 ${errors} 条`)

  // 统计各省报纸数量
  const stats = await prisma.$queryRaw`
    SELECT province, COUNT(*) as count 
    FROM newspapers 
    WHERE status = 1 
    GROUP BY province 
    ORDER BY count DESC
  `
  console.log('\n📍 各省报纸数量:')
  for (const row of stats) {
    const count = Number(row.count)
    const bar = '█'.repeat(Math.min(count, 20))
    console.log(`  ${String(row.province).padEnd(6)} ${String(count).padStart(3)} ${bar}`)
  }
  console.log(`\n总计: ${stats.reduce((sum, r) => sum + Number(r.count), 0)} 份`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
